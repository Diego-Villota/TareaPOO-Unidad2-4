/**
 * Class Documental
 */
package uni1a;

// Subclase Documental que extiende de ContenidoAudiovisual
public class Documental extends ContenidoAudiovisual {
    private String tema;
    private final java.util.List<Investigador> investigadores = new java.util.ArrayList<>();

    public void agregarInvestigador(Investigador investigador) { investigadores.add(java.util.Objects.requireNonNull(investigador)); }
    public java.util.List<Investigador> getInvestigadores() { return java.util.Collections.unmodifiableList(investigadores); }

    public Documental(String titulo, int duracionEnMinutos, String genero, String tema) {
        super(titulo, duracionEnMinutos, genero);
        this.tema = tema;
    }

    public String getTema() {
        return tema;
    }

    public void setTema(String tema) {
        this.tema = tema;
    }
    
    @Override
    public void mostrarDetalles() {
        System.out.println("Detalles del documental:");
        System.out.println("ID: " + getId());
        System.out.println("Título: " + getTitulo());
        System.out.println("Duración en minutos: " + getDuracionEnMinutos());
        System.out.println("Género: " + getGenero());
        System.out.println("Tema: " + this.tema);
        System.out.println("Investigadores: " + investigadores);
        System.out.println();
    }
}